                        <div className="flex items-center gap-2">
                            <h3 className="font-black text-white text-base sm:text-lg tracking-wide">
                                Quotation Management Mail Report
                            </h3>
                            <span className="bg-indigo-500/30 border border-indigo-400/30 text-indigo-200 text-xs font-bold px-2 py-0.5 rounded">
                                {dateRangeLabel}
                            </span>
                        </div>
